"""Domain-neutral disclosure prompts with strict section boundaries."""
from __future__ import annotations


V5_SYSTEM_PROMPT = """你是资深中文专利技术交底书撰写专家。

仅使用输入的当前案例证据，不得借用示例、其他案例或固定领域模板。
每个技术判断必须可追溯到所给事实；不得编造参数、关系、效果或实验结果。

章节边界：
- 背景技术：现有技术路线、客观不足及待解决问题，不提前展开本方案步骤。
- 发明内容：技术问题、总体构思、主要手段和有益效果，不重复背景史。
- 技术方案详细说明：按输入、处理、条件、参数、输出和衔接关系完整说明。
- 附图说明：逐图说明图题、用途和图中已声明关系。
- 具体实施方式：仅依据证据给出可执行步骤和可确认的条件。
- 代理机构说明：列出创新点、术语、证据位置和支持风险。
- 待确认信息：仅列材料缺失且需要人工确认的事项。

全部使用简体中文专利表达；不得使用宣传用语或学术论文口吻。技术术语以当前
案例术语注册表为准。只输出正文段落，段落间空行，不输出章节标题。
"""


_SECTION_GOALS = {
    "SEC03": "说明现有技术类别、与当前问题直接相关的客观不足，以及需要解决的技术问题。",
    "SEC04": "说明技术问题、总体技术构思、主要技术手段及其有证据支持的技术效果。",
    "SEC05": "按照事实声明的技术链，逐环节说明输入、处理、条件、参数、输出和上下游关系。",
    "SEC06": "逐图说明用途、来源以及图中节点与连接所表达的技术关系。",
    "SEC07": "将证据支持的技术内容组织为可执行实施步骤，不补造材料没有的数值。",
    "SEC08": "列出代理师需关注的核心特征、术语边界、证据位置和支持风险。",
    "SEC09": "列出材料缺失且需要发明人或代理机构确认的信息，并标明优先级。",
}


def v5_section_prompt(section_id: str, title_cn: str, evidence_text: str) -> str:
    """Build a section prompt from section semantics and current evidence."""
    goal = _SECTION_GOALS.get(
        section_id,
        "仅在本章节职责范围内组织当前案例证据，不重复其他章节内容。",
    )
    return (
        f"请撰写“{title_cn}”章节。\n\n"
        f"章节目标：{goal}\n"
        "要求：只使用下列当前案例材料；保持事实、公式、符号和数值；"
        "信息不足时明确列为待确认，不得用领域惯例补齐。\n\n"
        f"当前案例证据：\n{evidence_text[:8000]}"
    )
